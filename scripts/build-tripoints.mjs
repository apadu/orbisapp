/**
 * Finds every point where exactly three countries meet (land tripoints) in the
 * Natural Earth 50m countries file and writes src/data/tripoints.js.
 *
 *   node scripts/build-tripoints.mjs            (needs: npm i --no-save topojson-server)
 *
 * A tripoint is a topology junction (shared arc endpoint) used by arcs of three
 * different countries. Names follow the app (NAME_OVERRIDES in App.jsx); the game
 * drops any tripoint whose countries aren't all playable.
 */
import fs from 'node:fs'
import { topology } from 'topojson-server'
import { geoArea } from 'd3-geo'

const SRC = 'public/data/ne_50m_admin_0_countries.geojson'
const OUT = 'src/data/tripoints.js'
// The app's renames (NAME_OVERRIDES in App.jsx), plus Somaliland: its borders are Somalia's in the game
const app = fs.readFileSync('src/App.jsx', 'utf8')
const block = app.slice(app.indexOf('const NAME_OVERRIDES = {'), app.indexOf('}', app.indexOf('const NAME_OVERRIDES = {')))
const RENAME = { Somaliland: 'Somalia' }
for (const m of block.matchAll(/(['"])(.+?)\1:\s*(['"])(.+?)\3/g)) RENAME[m[2]] = m[4]
const SKIP = new Set(['Siachen Glacier', 'W. Sahara', 'N. Cyprus', 'Antarctica', 'Western Sahara'])

// Playable countries: the same filters App.jsx applies to the globe's country list
const setOf = (name) => {
  const i = app.indexOf(`const ${name} = new Set([`)
  return new Set([...app.slice(i, app.indexOf('])', i)).matchAll(/'([^']+)'/g)].map(m => m[1]))
}
const DROP_TYPES = setOf('DROP_TYPES'), KEEP_ALWAYS = setOf('KEEP_ALWAYS')
const EXCLUDE_NAMES = setOf('EXCLUDE_NAMES'), DISPLAY_ONLY = setOf('DISPLAY_ONLY')

const geo = JSON.parse(fs.readFileSync(SRC, 'utf8'))
const feats = geo.features.filter(f => f.geometry)
const playable = new Set(feats
  .filter(f => (KEEP_ALWAYS.has(f.properties.NAME) || !DROP_TYPES.has(f.properties.TYPE)) && !EXCLUDE_NAMES.has(f.properties.NAME))
  .map(f => RENAME[f.properties.NAME] ?? f.properties.NAME)
  .filter(n => !DISPLAY_ONLY.has(n)))
playable.add('Somalia')
const names = feats.map(f => RENAME[f.properties.NAME] ?? f.properties.NAME)
const topo = topology({ c: { type: 'FeatureCollection', features: feats } })   // exact, no quantization

// arc index → countries using it
const arcUsers = topo.arcs.map(() => new Set())
const walk = (a, n) => Array.isArray(a) ? a.forEach(x => walk(x, n)) : arcUsers[a < 0 ? ~a : a].add(n)
topo.objects.c.geometries.forEach((g, i) => g.arcs && walk(g.arcs, names[i]))

// junction coordinate → countries
const at = new Map()
topo.arcs.forEach((arc, i) => {
  for (const p of [arc[0], arc[arc.length - 1]]) {
    const k = p.join(',')
    if (!at.has(k)) at.set(k, new Set())
    for (const n of arcUsers[i]) at.get(k).add(n)
  }
})

const area = Object.fromEntries(feats.map((f, i) => [names[i], geoArea(f)]))
const seen = new Map()
for (const [k, set] of at) {
  if (set.size !== 3 || [...set].some(n => SKIP.has(n) || !playable.has(n))) continue
  const countries = [...set].sort()
  const key = countries.join('|')
  const [lon, lat] = k.split(',').map(Number)
  if (seen.has(key)) { seen.get(key).alt = (seen.get(key).alt ?? 0) + 1; continue }
  // view radius: big enough to show a real piece of the smallest country
  const minKm2 = Math.min(...countries.map(n => area[n] * 6371 ** 2))
  const radiusKm = Math.round(Math.min(380, Math.max(45, Math.sqrt(minKm2) * 0.55)))
  seen.set(key, { countries, lon: +lon.toFixed(4), lat: +lat.toFixed(4), radiusKm })
}
const list = [...seen.values()]
console.log('tripoints:', list.length, 'triples meeting twice:', list.filter(x => x.alt).map(x => x.countries.join('/')))
for (const x of list) delete x.alt
fs.writeFileSync(OUT, `// Generated by scripts/build-tripoints.mjs — every land point where three countries meet.\n// { countries: [a, b, c] (Natural Earth names), lon, lat, radiusKm (map view) }\nexport const TRIPOINTS = ${JSON.stringify(list, null, 0).replace(/\},\{/g, '},\n  {').replace('[{', '[\n  {').replace(/\}\]$/, '},\n]')}\n`)
